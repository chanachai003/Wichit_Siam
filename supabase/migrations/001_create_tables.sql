BEGIN;

-- 1. Users table
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username TEXT UNIQUE NOT NULL,
    password TEXT NOT NULL,
    role TEXT NOT NULL DEFAULT 'user',
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- 2. Photos table
CREATE TABLE IF NOT EXISTS public.photos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    description TEXT NOT NULL,
    province TEXT NOT NULL,
    region TEXT NOT NULL,
    date TEXT NOT NULL,
    activity TEXT NOT NULL,
    latitude DOUBLE PRECISION NOT NULL,
    longitude DOUBLE PRECISION NOT NULL,
    image_url TEXT NOT NULL,
    created_by BIGINT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT photos_created_by_fkey
        FOREIGN KEY (created_by)
        REFERENCES public.users(id)
        ON DELETE CASCADE
);

-- 3. Indexes
CREATE INDEX IF NOT EXISTS idx_photos_province
    ON public.photos(province);

CREATE INDEX IF NOT EXISTS idx_photos_region
    ON public.photos(region);

CREATE INDEX IF NOT EXISTS idx_photos_created_by
    ON public.photos(created_by);

-- 4. Enable Row Level Security
ALTER TABLE public.users ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.photos ENABLE ROW LEVEL SECURITY;

-- 5. Remove direct table access from public API roles
REVOKE ALL PRIVILEGES ON TABLE public.users, public.photos
    FROM anon, authenticated;

-- 6. Allow the trusted backend service to access the tables
GRANT ALL PRIVILEGES ON TABLE public.users, public.photos
    TO service_role;

GRANT USAGE, SELECT, UPDATE
    ON SEQUENCE public.users_id_seq, public.photos_id_seq
    TO service_role;

COMMIT;